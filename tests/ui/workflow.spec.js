  await page.getByLabel('Reason for leave').fill('Eligibility validation');
  await page.screenshot({path:testInfo.outputPath('gender-eligibility-warning.png'),fullPage:true,animations:'disabled'});
  await page.getByRole('button',{name:'Submit application'}).click();
  await expect(page.locator('tbody .badge.rejected')).toHaveCount(1);
  const rejected=page.getByRole('row').filter({has:page.locator('.badge.rejected')});
  await rejected.getByRole('button',{name:'View',exact:true}).click();
  await expect(page.getByText(/Automatic eligibility check/)).toBeVisible();
  await expect(page.getByRole('dialog').getByText(/Automatically rejected: Paternity leave/)).toBeVisible();
  await page.getByRole('button',{name:'Close dialog'}).click();
  await nav('Leave credits');
  await expect(page.getByRole('row').filter({hasText:'Vacation leave'}).getByText('13 days')).toBeVisible();
