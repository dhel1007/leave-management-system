  await page.getByRole('button',{name:'Add leave type',exact:true}).click();
  await page.getByLabel('Leave type name').fill('Paternity leave');
  await page.getByLabel('Short code').fill('PL');
  await expect(page.getByLabel('Gender eligibility')).toHaveValue('male');
  await page.getByRole('button',{name:'Save changes'}).click();
  await expect(page.getByText('Male only',{exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Add leave type',exact:true}).click();
  await page.getByLabel('Leave type name').fill('Maternity leave');
  await page.getByLabel('Short code').fill('ML');
  await expect(page.getByLabel('Gender eligibility')).toHaveValue('female');
  await page.getByRole('button',{name:'Save changes'}).click();
  await expect(page.getByText('Female only',{exact:true})).toBeVisible();
  await nav('User accounts');
  await page.getByRole('button',{name:'Add account'}).click();
  await page.getByLabel('Display name').fill('Maria Reyes');
  await page.getByLabel('Username',{exact:true}).fill('hr');
  await page.getByLabel('Role',{exact:true}).selectOption('hr');
  await page.getByLabel('Temporary password (12+ characters)').fill('TemporaryHR!2026');
  await page.getByRole('button',{name:'Save changes'}).click();
