test('working dates exclude weekends and holidays and support half days',()=>{
  assert.equal(workingDays('2026-10-09','2026-10-13',['2026-10-12']),2);
  assert.equal(workingDays('2026-10-13','2026-10-13',[],true),.5);
  assert.equal(workingDays('2026-10-10','2026-10-11'),0);
  assert.throws(()=>workingDays('2026-10-13','2026-10-14',[],true));
  assert.throws(()=>workingDays('2026-12-31','2027-01-01'));
  assert.throws(()=>workingDays('2026-02-30','2026-03-01'));
  assert.equal(validDate('2026-02-30'),false);
  assert.equal(validDate('2028-02-29'),true);
});

