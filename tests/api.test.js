test('SQLite records persist when the database is reopened',()=>{
  const folder=mkdtempSync(join(tmpdir(),'agency-leave-'));
  const path=join(folder,'persist.sqlite');
  try {
    let db=openDatabase(path);
    db.prepare('INSERT INTO holidays VALUES(?,?)').run('2026-10-12','Saved holiday');
    db.close();
    db=openDatabase(path);
    assert.equal(db.prepare('SELECT name FROM holidays WHERE date=?').get('2026-10-12').name,'Saved holiday');
    assert.equal(db.prepare('SELECT COUNT(*) total FROM users').get().total,1);
    db.close();
  } finally {rmSync(folder,{recursive:true,force:true});}
});
